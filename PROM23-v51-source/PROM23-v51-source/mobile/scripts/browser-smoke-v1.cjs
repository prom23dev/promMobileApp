// Run after export and preview-server.cjs. Uses an isolated headless Chrome profile.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let playwright;
try { playwright = require('playwright'); }
catch { playwright = require('/Users/prom23/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'); }
const output = path.resolve(__dirname, '../../docs/screenshots');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await playwright.chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto('http://127.0.0.1:8087');
    await page.getByText('Для вашей стройки', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'home-390.png') });
    checks.push('Главная загружается без JS-ошибок');
    await page.getByRole('tab', { name: 'Каталог', exact: true }).click();
    await page.getByRole('textbox', { name: 'Поиск по названию или артикулу' }).fill('DEMO-003');
    await page.getByText('Товаров: 1 · демонстрационный каталог', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'В избранное: Лестница алюминиевая, 3 секции', exact: true }).click();
    await page.getByRole('button', { name: 'В корзину', exact: true }).click();
    await page.getByRole('button', { name: 'Увеличить количество: Лестница алюминиевая, 3 секции', exact: true }).click();
    checks.push('Поиск по артикулу, избранное и изменение количества');
    await page.getByRole('button', { name: 'Открыть товар: Лестница алюминиевая, 3 секции', exact: true }).click();
    await page.getByText('Характеристики', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'product-390.png') });
    await page.getByRole('button', { name: 'Назад', exact: true }).click();
    await page.getByRole('tab', { name: /^Корзина/ }).click();
    await page.getByText('Покупки для себя · 2 ед.', { exact: true }).waitFor();
    assert((await page.getByText(/17\s500\s₽/).count()) > 0);
    await page.screenshot({ path: path.join(output, 'cart-390.png') });
    await page.getByRole('button', { name: 'Посмотреть расчёт', exact: true }).click();
    await page.getByText('Расчёт демонстрационной корзины', { exact: true }).waitFor();
    assert.equal(await page.getByRole('textbox').count(), 0);
    await page.getByRole('button', { name: 'Вернуться в корзину', exact: true }).click();
    await page.getByRole('radio', { name: 'Для компании', exact: true }).click();
    await page.getByText('Здесь будет ваш заказ', { exact: true }).waitFor();
    await page.getByRole('radio', { name: 'Для себя', exact: true }).click();
    await page.getByText('Покупки для себя · 2 ед.', { exact: true }).waitFor();
    checks.push('Сумма 17 500 ₽, честный checkout, изоляция и восстановление контекстных корзин');
    await page.getByRole('tab', { name: 'Избранное', exact: true }).click();
    await page.getByRole('button', { name: 'Сравнить: Лестница алюминиевая, 3 секции', exact: true }).click();
    await page.getByRole('button', { name: 'Открыть сравнение. Товаров: 1', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'compare-390.png') });
    await page.getByRole('button', { name: 'Назад', exact: true }).click();
    checks.push('Избранное и открытие сравнения');
    await page.getByRole('tab', { name: 'Главная', exact: true }).click();
    await page.getByRole('button', { name: 'Город: Краснодар. Выбрать город', exact: true }).click();
    await page.getByRole('radio', { name: 'Ростов-на-Дону', exact: true }).click();
    await page.setViewportSize({ width: 320, height: 760 });
    const brand = await page.getByText('Промышленник', { exact: true }).boundingBox();
    const city = await page.getByRole('button', { name: 'Город: Ростов-на-Дону. Выбрать город', exact: true }).boundingBox();
    assert(brand && city && brand.x + brand.width <= city.x + 1, 'Brand overlaps city at 320px');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Horizontal page overflow');
    await page.screenshot({ path: path.join(output, 'home-320.png') });
    await page.setViewportSize({ width: 768, height: 1024 });
    await page.screenshot({ path: path.join(output, 'home-768.png') });
    checks.push('Выбор города, ширины 320/390/768 без горизонтального переполнения страницы');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('tab', { name: 'Кабинет', exact: true }).click();
    await page.getByRole('button', { name: 'Заказы и доставка. Узнать статус подключения', exact: true }).click();
    await page.getByText('Интеграция ещё не выполнена', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Понятно', exact: true }).click();
    await page.getByRole('button', { name: 'Сбросить демо-данные', exact: true }).click();
    await page.getByRole('button', { name: 'Сбросить демо-данные', exact: true }).last().click();
    await page.getByRole('tab', { name: /^Корзина/ }).click();
    await page.getByText('Здесь будет ваш заказ', { exact: true }).waitFor();
    checks.push('Кабинет показывает статус интеграции; подтверждённый сброс очищает демо');
    await page.goto('http://127.0.0.1:8087/product/missing');
    await page.getByText('Товар не найден', { exact: true }).waitFor();
    checks.push('Неизвестный product deep link обрабатывается');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.resolve(output, '../browser-smoke.json'), JSON.stringify({ date: new Date().toISOString(), checks, errors }, null, 2));
    console.log(JSON.stringify({ checks, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
